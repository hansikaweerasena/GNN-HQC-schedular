def compute_reduction(data):
    """Compute EFCL reduction (%) vs best baseline for each N."""
    ns = sorted(data.keys())
    reductions = []
    for n in ns:
        mosaic, b1, b3, b4, b5 = data[n]
        best_base = min(b1, b3, b4, b5)
        reduction = (1.0 - mosaic / best_base) * 100.0
        reductions.append(reduction)
    return ns, reductions


